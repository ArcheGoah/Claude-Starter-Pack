// ============================================================================
// Audio Analyser Hook (AudioWorklet-based, 2026 standard)
// ============================================================================

function useAudioAnalyser(enabled: boolean, source: 'microphone' | 'element', el?: HTMLAudioElement) {
  const analyserRef = useRef<AnalyserNode | null>(null)
  const dataRef = useRef<Uint8Array>(new Uint8Array(128))
  const [error, setError] = useState<string | null>(null)

  useEffect(() => {
    if (!enabled) return

    let ctx: AudioContext | null = null
    let stream: MediaStream | null = null
    let mounted = true

    const init = async () => {
      try {
        ctx = new AudioContext()
        const analyser = ctx.createAnalyser()
        analyser.fftSize = 256
        analyser.smoothingTimeConstant = 0.8

        if (source === 'microphone') {
          stream = await navigator.mediaDevices.getUserMedia({ audio: true })
          const src = ctx.createMediaStreamSource(stream)
          src.connect(analyser)
        } else if (el) {
          const src = ctx.createMediaElementSource(el)
          src.connect(analyser)
          analyser.connect(ctx.destination)
        }

        if (mounted) {
          analyserRef.current = analyser
          dataRef.current = new Uint8Array(analyser.frequencyBinCount)
        }
      } catch (e) {
        setError(e instanceof Error ? e.message : 'Audio init failed')
      }
    }

    // Require user gesture — defer until first interaction
    const onGesture = () => {
      init()
      window.removeEventListener('pointerdown', onGesture)
    }
    window.addEventListener('pointerdown', onGesture)

    return () => {
      mounted = false
      window.removeEventListener('pointerdown', onGesture)
      stream?.getTracks().forEach((t) => t.stop())
      ctx?.close()
      analyserRef.current = null
    }
  }, [enabled, source, el])

  const getBands = useCallback(() => {
    const a = analyserRef.current
    if (!a) return { bass: 0, mid: 0, high: 0 }
    a.getByteFrequencyData(dataRef.current)
    const d = dataRef.current
    const slice = (start: number, end: number) => {
      let sum = 0
      for (let i = start; i < end; i++) sum += d[i]
      return sum / (end - start) / 255
    }
    return {
      bass: slice(0, 8),
      mid:  slice(8, 40),
      high: slice(40, 100),
    }
  }, [])

  return { getBands, error }
}

// ============================================================================
// Compute Particle System (TSL)
// ============================================================================

interface ParticlesProps {
  count: number
  mode: ParticleMode
  getBands: () => { bass: number; mid: number; high: number }
}

function ComputeParticles({ count, mode, getBands }: ParticlesProps) {
  const { gl } = useThree() as { gl: THREE.WebGPURenderer }
  const meshRef = useRef<THREE.Mesh>(null)
  const disposablesRef = useRef<Array<{ dispose?: () => void }>>([])

  // Uniforms — mutate from useFrame, never setState
  const uBass = useMemo(() => uniform(0), [])
  const uMid  = useMemo(() => uniform(0), [])
  const uHigh = useMemo(() => uniform(0), [])
  const uMouse = useMemo(() => uniform(vec3(0, 0, 0)), [])
  const uColorA = useMemo(() => uniform(vec3(BRAND.primary.r, BRAND.primary.g, BRAND.primary.b)), [])
  const uColorB = useMemo(() => uniform(vec3(BRAND.accent.r,  BRAND.accent.g,  BRAND.accent.b)),  [])
  const uColorC = useMemo(() => uniform(vec3(BRAND.gold.r,    BRAND.gold.g,    BRAND.gold.b)),    [])

  // Storage buffers — Position + Velocity (Compute Shader state)
  const { positionBuffer, velocityBuffer, particleMaterial, computeInit, computeUpdate } = useMemo(() => {
    const positions = new Float32Array(count * 3)
    const velocities = new Float32Array(count * 3)
    for (let i = 0; i < count; i++) {
      positions[i * 3 + 0] = (Math.random() - 0.5) * 20
      positions[i * 3 + 1] = (Math.random() - 0.5) * 20
      positions[i * 3 + 2] = (Math.random() - 0.5) * 20
    }

    const positionBuffer = storage(
      new THREE.StorageBufferAttribute(positions, 3),
      'vec3',
      count
    )
    const velocityBuffer = storage(
      new THREE.StorageBufferAttribute(velocities, 3),
      'vec3',
      count
    )

    // Init compute — random sphere distribution
    const computeInit = Fn(() => {
      const pos = positionBuffer.element(instanceIndex)
      const h = hash(instanceIndex)
      pos.assign(vec3(
        h.mul(2).sub(1),
        hash(instanceIndex.add(1)).mul(2).sub(1),
        hash(instanceIndex.add(2)).mul(2).sub(1),
      ).normalize().mul(float(5).add(h.mul(3))))
    })().compute(count)

    // Update compute — curl noise + audio-reactive forces
    const computeUpdate = Fn(() => {
      const pos = positionBuffer.element(instanceIndex)
      const vel = velocityBuffer.element(instanceIndex)

      // Curl noise field
      const noise = mx_noise_float(pos.mul(0.3).add(time.mul(0.2)))
      const force = vec3(
        sin(pos.y.mul(0.5).add(time)),
        cos(pos.z.mul(0.5).add(time)),
        sin(pos.x.mul(0.5).add(time)),
      ).mul(noise).mul(0.02)

      // Audio-reactive bass push
      const bassForce = normalize(pos).mul(uBass).mul(0.3)
      vel.addAssign(force).addAssign(bassForce)
      vel.mulAssign(0.96) // damping
      pos.addAssign(vel)

      // Bounds — wrap around sphere
      const dist = length(pos)
      If(dist.greaterThan(15), () => {
        pos.assign(normalize(pos).mul(15))
        vel.mulAssign(-0.5)
      })
    })().compute(count)

    // Material — TSL with instance color via noise + audio mid
    const material = new THREE.SpriteNodeMaterial({
      transparent: true,
      depthWrite: false,
      blending: THREE.AdditiveBlending,
    })
    material.positionNode = positionBuffer.toAttribute()

    const colorMix = mix(uColorA, uColorB, hash(instanceIndex))
    const audioTint = mix(colorMix, uColorC, uMid)
    material.colorNode = vec4(audioTint, float(0.8).sub(uHigh.mul(0.3)))
    material.scaleNode = float(0.05).add(uBass.mul(0.1))

    return { positionBuffer, velocityBuffer, particleMaterial: material, computeInit, computeUpdate }
  }, [count, uBass, uMid, uHigh, uColorA, uColorB, uColorC])

  // Init compute once
  useEffect(() => {
    gl.computeAsync(computeInit)
    disposablesRef.current.push(particleMaterial, computeInit, computeUpdate)
  }, [gl, computeInit, computeUpdate, particleMaterial])

  // Per-frame update
  useFrame(() => {
    const bands = getBands()
    uBass.value = bands.bass
    uMid.value  = bands.mid
    uHigh.value = bands.high
    gl.computeAsync(computeUpdate)
  })

  // Cleanup
  useEffect(() => () => {
    disposablesRef.current.forEach((d) => d.dispose?.())
    disposablesRef.current = []
  }, [])

  return (
    <sprite ref={meshRef as never}>
      <planeGeometry args={[1, 1]} />
      <primitive object={particleMaterial} attach="material" />
    </sprite>
  )
}

// ============================================================================
// Fallback (WebGL2 / low-end GPU) — simple Points
// ============================================================================

function FallbackParticles({ count }: { count: number }) {
  const pointsRef = useRef<THREE.Points>(null)
  const geo = useMemo(() => {
    const g = new THREE.BufferGeometry()
    const positions = new Float32Array(count * 3)
    for (let i = 0; i < count; i++) {
      positions[i * 3 + 0] = (Math.random() - 0.5) * 20
      positions[i * 3 + 1] = (Math.random() - 0.5) * 20
      positions[i * 3 + 2] = (Math.random() - 0.5) * 20
    }
    g.setAttribute('position', new THREE.BufferAttribute(positions, 3))
    return g
  }, [count])

  const mat = useMemo(() => new THREE.PointsMaterial({
    color: BRAND.primary,
    size: 0.05,
    transparent: true,
    opacity: 0.8,
    blending: THREE.AdditiveBlending,
  }), [])

  useFrame(({ clock }) => {
    if (pointsRef.current) {
      pointsRef.current.rotation.y = clock.elapsedTime * 0.05
    }
  })

  useEffect(() => () => {
    geo.dispose()
    mat.dispose()
  }, [geo, mat])

  return <points ref={pointsRef} geometry={geo} material={mat} />
}

// ============================================================================
// Main Exported Component
// ============================================================================

export default function ParticleHero({
  mode = 'default',
  particleCount,
  audioSource = 'microphone',
  audioElement,
  className = 'w-full h-screen',
  showPerf = false,
}: ParticleHeroProps) {
  const [tier, setTier] = useState<TierResult | null>(null)
  const [webgpuSupported, setWebgpuSupported] = useState<boolean | null>(null)

  // GPU detection on mount
  useEffect(() => {
    getGPUTier().then(setTier)
    setWebgpuSupported(typeof navigator !== 'undefined' && 'gpu' in navigator)
  }, [])

  // Audio analyser (only if mode === 'audio-reactive')
  const { getBands, error: audioError } = useAudioAnalyser(
    mode === 'audio-reactive',
    audioSource,
    audioElement
  )

  // Adaptive particle count
  const count = useMemo(() => {
    if (particleCount) return particleCount
    if (!tier) return 50_000
    if (tier.tier >= 3 && webgpuSupported) return 1_000_000
    if (tier.tier === 2) return 250_000
    return 50_000
  }, [particleCount, tier, webgpuSupported])

  if (tier === null || webgpuSupported === null) {
    return <div className={`${className} bg-black`} aria-label="Loading hero" />
  }

  return (
    <div className={className} role="img" aria-label="Interactive particle hero background">
      <Canvas
        gl={async (props) => {
          const renderer = webgpuSupported
            ? new THREE.WebGPURenderer(props as THREE.WebGPURendererParameters)
            : new THREE.WebGLRenderer(props as THREE.WebGLRendererParameters)
          await (renderer as THREE.WebGPURenderer).init?.()
          return renderer as unknown as THREE.WebGLRenderer
        }}
        camera={{ position: [0, 0, 25], fov: 60 }}
        dpr={[1, tier.tier >= 3 ? 2 : 1]}
      >
        {webgpuSupported ? (
          <ComputeParticles count={count} mode={mode} getBands={getBands} />
        ) : (
          <FallbackParticles count={Math.min(count, 100_000)} />
        )}
        {showPerf && process.env.NODE_ENV === 'development' && <Perf position="top-left" />}
      </Canvas>
      {audioError && (
        <div className="absolute bottom-4 left-4 text-xs text-white/60 bg-black/40 px-3 py-1 rounded">
          Audio: {audioError} (Fallback aktiv)
        </div>
      )}
    </div>
  )
}
